"""Build the library and its standalone dictionaries."""
import html
import json
from pathlib import Path
import re
import tempfile
import sys

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "public"
sys.path.insert(0, str(ROOT / "skills/skill-dictionary/scripts"))
from render import render, style_document


def generate(output):
    library = []
    seen = set()
    for path in sorted((ROOT / "catalogs").glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        slug = data["id"]
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug) or slug in seen:
            raise ValueError(f"Invalid or duplicate collection id in {path.name}")
        seen.add(slug)
        directory = output / slug
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "index.html").write_text(render(data), encoding="utf-8")
        library.append({key: data[key] for key in ("id", "title", "description")} | {
            "items": [{key: item.get(key) for key in ("id", "name", "summary", "category", "when", "keywords")} for item in data["items"]]
        })
    if not library:
        raise ValueError("No catalogs found")
    template = (ROOT / "site/index.html").read_text(encoding="utf-8")
    encoded = json.dumps(library, ensure_ascii=False).replace("<", r"\u003c")
    links = "".join(f'<a class="collection" href="{d["id"]}/index.html"><span><strong>{html.escape(d["title"])}</strong><small>{html.escape(d["description"])}</small></span><b>{len(d["items"])}개 ↗</b></a>' for d in library)
    page = template.replace("<!--COLLECTIONS-->", links).replace("/*CATALOGS*/", encoded)
    (output / "index.html").write_text(style_document(page), encoding="utf-8")


def build():
    # Only remove retired pages previously generated by this builder.
    OUTPUT.mkdir(exist_ok=True)
    manifest = OUTPUT / ".generated-pages.json"
    previous = json.loads(manifest.read_text()) if manifest.exists() else []
    with tempfile.TemporaryDirectory(dir=OUTPUT.parent) as temporary:
        staging = Path(temporary)
        generate(staging)
        pages = sorted(p.relative_to(staging).as_posix() for p in staging.rglob("index.html"))
        for name in pages:
            destination = OUTPUT / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            (staging / name).replace(destination)
        for name in set(previous) - set(pages):
            if re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*/index\.html", name):
                (OUTPUT / name).unlink(missing_ok=True)
        record = staging / "pages.json"
        record.write_text(json.dumps(pages), encoding="utf-8")
        record.replace(manifest)


if __name__ == "__main__":
    build()
